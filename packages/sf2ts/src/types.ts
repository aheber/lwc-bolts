// sf2ts's public types, which index.ts exports. Its own module, importing nothing, so the modules that
// use them don't import index.ts, which imports them.

/** The metadata types sf2ts converts, each by its converter (see converters/registry.ts). */
export type MetadataType =
  | "ApexClass"
  | "ContentAsset"
  | "CustomField"
  | "CustomLabel"
  | "CustomLabels"
  | "CustomObject"
  | "CustomPermission"
  | "LightningComponentBundle"
  | "LightningMessageChannel"
  | "StaticResource";

/** What becomes of an Apex class's fields LWC can't read (see `ConvertOptions.inaccessibleApexProperties`). */
export type InaccessibleApexProperties = "include" | "exclude" | "include as deprecated";

/**
 * A mapped piece of text is two consecutive pairs, its start and its end: where it is in the source
 * (`sourcePos`) and in the output (`destPos`), as UTF-16 offsets.
 */
export interface MapPair {
  sourcePos: number;
  destPos: number;
  /**
   * On a piece's start: the editor features it takes part in, as TypeScript's `SpanMapFeature` flags
   * (see `MapFeature`). Without them, it takes part in all of them.
   */
  features?: number;
}

/**
 * A file to convert, by its metadata type. The options only some types take are on their own
 * components: `ApexClassComponent` and `LightningComponentBundleComponent`.
 */
export type Component = ApexClassComponent | LightningComponentBundleComponent | MetadataComponent;

/** What every component has: its file's path and content. */
interface ComponentFile {
  path: string;
  content: string;
}

/** A component of a type that takes no options of its own. */
export interface MetadataComponent extends ComponentFile {
  type: Exclude<MetadataType, "ApexClass" | "LightningComponentBundle">;
}

/**
 * A file of a Lightning web component bundle. sf2ts only reads the file itself: what it needs to know about
 * the rest of the bundle is given here, which the caller finds out (`bundleApiVersion` and
 * `defaultExportName` read it from the bundle's other files).
 */
export interface LightningComponentBundleComponent extends ComponentFile {
  type: "LightningComponentBundle";
  /**
   * For a template (an `.html` file), the module it imports its bundle's component through, relative to the
   * template: `./orders.js` (which TypeScript also resolves to `orders.ts`), or `../orders.js` from a
   * subfolder of the bundle. Templates are matched to their bundle's class, as LWC does, so a bundle's
   * alternate templates (rendered from `render()`) work too. Without it, the template is taken to be in the
   * bundle's folder: `./<bundleName>.js`.
   */
  componentModule?: string;
  /**
   * For a template, the bundle's name (its folder's: `orders`, or an installed package's `dlrs__orders`),
   * which names the `c/<name>` module it declares its slots under. Without it, the template's folder's name.
   */
  bundleName?: string;
  /**
   * For a template, the bundle's API version, from its `.js-meta.xml` (see `bundleApiVersion`), which the
   * template is parsed at: the template compiler's latest without it.
   */
  apiVersion?: number;
  /**
   * For a template, whether the bundle has other templates, any of which may be the one rendered, which
   * makes every `lwc:ref` optional.
   */
  alternateTemplates?: boolean;
  /**
   * For a `.js-meta.xml`, the name of the bundle's module's default export (see `defaultExportName`),
   * which names the `c/<name>` module's export, as editors suggest it when auto-importing: the bundle's
   * name without it.
   */
  defaultExportName?: string;
}

export interface ApexClassComponent extends ComponentFile {
  type: "ApexClass";
  /**
   * Whether it is an SObject definition generated by the Salesforce extensions
   * (`.sfdx/tools/sobjects`). Its fields are exposed without `@AuraEnabled`, and it declares no
   * `@salesforce/apex` modules.
   */
  isSobject?: boolean;
  /**
   * For an SObject definition, the objects each polymorphic relationship (such as Task's `What`, declared
   * as `SObject`) can refer to, by relationship name: `{ What: ["Account", "Case"] }`. Each is typed as one
   * of its targets once all of them are declared, with the `Name` object's fields when it's declared too;
   * TypeScript finds out which are. Others stay `SObject`.
   */
  polymorphicTargets?: Readonly<Record<string, readonly string[]>>;
}

/**
 * A problem in a component's file, at a UTF-16 offset and length in its content: `ConversionFailed` when
 * the file couldn't be converted (covering the whole file, with empty output), or `TemplateError` for an
 * error the LWC template compiler reports in a template.
 */
export interface Diagnostic {
  kind: "ConversionFailed" | "TemplateError";
  message: string;
  start: number;
  length: number;
}

/**
 * A converted file. Metadata becomes declarations in a global script (`declare module "@salesforce/..."`
 * and `declare namespace Apex`); a template becomes a module that imports its component and uses it the
 * way the template does, so TypeScript checks the template against it. A file that declares nothing
 * (such as an Apex interface) has empty `text`.
 */
export type ConvertedComponent = Component & ConversionOutput;

/** What a file converts to: its TypeScript, the mapped pieces of it, and any problems. */
export interface ConversionOutput {
  text: string;
  mapData: MapPair[];
  diagnostics?: Diagnostic[];
}

export interface ConvertOptions {
  /**
   * The namespace Apex types are declared in, which may be dotted (`Org.Apex`). Defaults to `"Apex"`;
   * `null` declares them globally, where a class can merge with a global type of the same name (such as
   * the DOM's `Response`).
   */
  apexNamespace?: string | null;
  /**
   * What becomes of an Apex class's fields that LWC can't read (not `@AuraEnabled`, not `public` or
   * `global`, or `static`): `"include as deprecated"` (the default) declares them marked `@deprecated`
   * with what they'd need, so editors flag their use; `"include"` declares them like any other field;
   * `"exclude"` leaves them out. SObject definitions' fields are always declared.
   */
  inaccessibleApexProperties?: InaccessibleApexProperties;
  /**
   * The project's namespace, used to know when to add or hide namespaces for modules and components
   */
  projectNamespace?: string;
}
